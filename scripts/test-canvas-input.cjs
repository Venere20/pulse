const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const assert = require('node:assert/strict');
function surface(file, enabled = true) {
  const refs = [];
  const react = { useRef(value) { const ref = { current: value }; refs.push(ref); return ref; }, useEffect() {}, createElement(type, props, ...children) { return { type, props: { ...props, children } }; } };
  const module = { exports: {} };
  const source = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.React } }).outputText;
  const requireStub = name => name === 'react' ? react : name === 'react-native' ? { View: 'View' } : name === './Drawing' ? { Drawing: 'Drawing' } : {};
  vm.runInNewContext(source, { module, exports: module.exports, require: requireStub });
  const points = []; let ends = 0;
  const tree = module.exports.Surface({ strokes: [], enabled, onBegin: (x,y) => points.push(['begin', x,y]), onPoint: (x,y) => points.push(['move',x,y]), onEnd: () => ends++ });
  return { props: tree.props, refs, points, ends: () => ends };
}
